def validate_cases() -> list[str]:
    """Проверить целостность кейсов (офлайн, без API)."""
    errors = []
    ids = set()
    from synth_kb import CHUNKS
    valid_ids = {c["id"] for c in CHUNKS}
    for c in CASES:
        if c["case_id"] in ids:
            errors.append(f"duplicate case_id {c['case_id']}")
        ids.add(c["case_id"])
        for cid in c["context_ids"]:
            if cid not in valid_ids:
                errors.append(f"{c['case_id']}: unknown context {cid}")
        if not c["required_facts"]:
            errors.append(f"{c['case_id']}: empty required_facts")
    return errors
