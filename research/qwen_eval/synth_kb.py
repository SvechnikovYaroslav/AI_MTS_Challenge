def get_chunk(cid: str) -> dict:
    for c in CHUNKS:
        if c["id"] == cid:
            return c
    raise KeyError(cid)


def format_context(chunk_ids: list[str]) -> str:
    """Собрать текст контекста для промпта (как делает RAG)."""
    parts = []
    for i, cid in enumerate(chunk_ids, 1):
        c = get_chunk(cid)
        parts.append(f"[{i}] {c['source']} — {c['section']}\n{c['text']}")
    return "\n\n".join(parts)
