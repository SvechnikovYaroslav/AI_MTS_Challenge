def validate_h5() -> list[str]:
    errors = []
    from synth_kb import CHUNKS
    valid = {c["id"] for c in CHUNKS}
    seen = set()
    for c in H5_CASES:
        if c["case_id"] in seen:
            errors.append(f"dup {c['case_id']}")
        seen.add(c["case_id"])
        for cid in c["context_ids"]:
            if cid not in valid:
                errors.append(f"{c['case_id']}: unknown {cid}")
        if not c["required_facts"]:
            errors.append(f"{c['case_id']}: empty required_facts")
    return errors
